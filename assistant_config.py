# Настройки помощника. Числа можно менять — бот возьмёт их при следующем запуске.

# ---------------------------------------------------------------- Стоп по графику
STOP_PIVOT_BARS_15M = 48     # где искать ближайший максимум (шорт) / минимум (лонг): 48 свечей 15м = 12 часов
STOP_BUFFER_ATR15 = 0.3      # запас за уровнем: 0.3 ATR(15м)
MIN_STOP_ATR15 = 1.0         # стоп ближе 1 ATR(15м) — это шум: бот отодвинет свой стоп и предупредит о вашем

# ---------------------------------------------------------------- Цели
TARGET_MIN_R = 1.0           # цель 1 не ближе 1R (R — расстояние до стопа)
FALLBACK_T1_R = 2.0          # если уровня нет: цель 1 = 2R
FALLBACK_T2_R = 3.0          # цель 2 = 3R
TAKE_AT_T1_PCT = 50          # сколько закрывать на цели 1

# ---------------------------------------------------------------- Сопровождение
BREAKEVEN_AT_R = 1.0         # после 1R — совет перенести стоп в безубыток
TRAIL_MIN_STEP_R = 0.25      # новый стоп по структуре 1ч советуется, если он лучше старого хотя бы на 0.25R
NEAR_STOP_R = 0.25           # цена в 0.25R от стопа — напоминание «не двигай стоп»
RSI_EXTREME = 25             # RSI(15м) ниже 25 для шорта (выше 75 для лонга) — возможен отскок
CHASE_PCT = 6.0              # цена уже прошла больше 6% за сутки в сторону сделки — «вход вдогонку»
TRACK_EVERY_SEC = 60         # как часто проверять цену, пока запуск работает
STOCK_WARN_MIN = 15          # за сколько минут до открытия биржи предупреждать (токены акций — STOCK_TOKENS в config.py)

# ---------------------------------------------------------------- Ликвидация (изолированная маржа, приблизительно)
MAINT_MARGIN_PCT = 0.5       # поддерживающая маржа OKX, % (у разных монет 0.4–1%)

# ---------------------------------------------------------------- Работа запуска
RUN_SECONDS = 270            # сколько секунд держит связь с Telegram один запуск (потом начинается следующий)
IGNORE_OLDER_MIN = 15        # при первом запуске (память пуста) команды старше 15 минут пропускаются
